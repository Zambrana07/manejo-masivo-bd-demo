  function L(texto) {
    if (texto == null) return "";
    const s = String(texto);
    if (FIJOS[s]) return t(FIJOS[s]);
    let m = s.match(/^Subfamilia (\d+)$/);
    if (m) return `${t("d.sub")} ${m[1]}`;
    m = s.match(/^Medida (\d+)$/);
    if (m) return `${t("d.unit")} ${m[1]}`;
    m = s.match(/^Estante(?: ejemplo)? (\d+)$/i);
    if (m) return `${t("d.shelf")} ${m[1]}`;
    m = s.match(/^Artículo demo (\d+)$/);
    if (m) return `${t("d.item")} ${m[1]}`;
    return s;
  }

  function LLargo(texto) {
    if (texto == null) return "";
    let out = String(texto);
    out = out.replace(/Utilidad\s+(\d+)\s*%/g, (_, n) => `${t("h.util")} ${n}%`);
    out = out.replace(/Aplica tienda:\s*marcar/gi, `${t("h.store")}: ${t("ui.mark").toLowerCase()}`);
    out = out.replace(/Aplica tienda:\s*quitar/gi, `${t("h.store")}: ${t("ui.unmark").toLowerCase()}`);
    out = out.replace(/Vigilante\s*·\s*sin stock/gi, `${t("ui.watch")} · ${t("h.outOfStock")}`);
    out = out.replace(/Sección A en vacíos/g, `${t("ui.secA")} ${t("h.emptySec")}`);
    out = out.replace(/desmarcados de tienda/g, t("h.uncheckedStore"));
    out = out.replace(/Kit creado/g, t("h.kitCreated"));
    out = out.replace(/Reversión demo/g, t("h.revertDemo"));
    out = out.replace(/Cambio en curso/g, t("h.running"));
    out = out.replace(/\(simulado\)/g, t("h.sim"));
    const pares = Object.entries(FIJOS)
      .map(([es, key]) => [es, t(key)])
      .sort((a, b) => b[0].length - a[0].length);
    pares.forEach(([es, tr]) => {
      if (es !== tr) out = out.split(es).join(tr);
    });
    out = out.replace(/Subfamilia (\d+)/g, (_, n) => `${t("d.sub")} ${n}`);
    out = out.replace(/Artículo demo (\d+)/g, (_, n) => `${t("d.item")} ${n}`);
    out = out.replace(/(\d+)\s+artículos/g, (_, n) => t("h.nItems", { n }));
    return out;
  }

  function aplicarNodo(el) {
    const key = el.getAttribute("data-i18n");
    if (key) {
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = t(key);
      else el.textContent = t(key);
    }
    const ph = el.getAttribute("data-i18n-placeholder");
    if (ph) el.setAttribute("placeholder", t(ph));
    const title = el.getAttribute("data-i18n-title");
    if (title) el.setAttribute("title", t(title));
    const aria = el.getAttribute("data-i18n-aria");
    if (aria) el.setAttribute("aria-label", t(aria));
  }

  function aplicar(opts = {}) {
    const animar = Boolean(opts.animar);
    if (animar) {
      document.dispatchEvent(new CustomEvent("idioma-cambiando", { detail: I18N.lang }));
    }
    document.documentElement.lang = I18N.lang;
    document.querySelectorAll("[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria]").forEach(aplicarNodo);
    document.querySelectorAll(".btn-idioma").forEach((btn) => {
      btn.textContent = t("lang.btn");
      btn.setAttribute("aria-label", t("lang.aria"));
    });
    document.dispatchEvent(new CustomEvent("idioma-cambiado", { detail: { lang: I18N.lang, animar } }));
  }

  function setLang(lang) {
    I18N.lang = lang === "en" ? "en" : "es";
    try { localStorage.setItem(LS, I18N.lang); } catch { /* ignore */ }
    aplicar({ animar: true });
  }

  function toggle() {
    setLang(I18N.lang === "es" ? "en" : "es");
  }

